type DeepPartial<T> = {
  [P in keyof T]?: T[P] extends (infer U)[]
    ? U[]
    : T[P] extends object
    ? DeepPartial<T[P]>
    : T[P];
};

const buildLocale = (
  custom: DeepPartial<Translations>,
  fallback: Translations
): Translations => {
  const result: any = { ...fallback };
  for (const key of Object.keys(custom)) {
    if (
      typeof (custom as any)[key] === 'object' &&
      !Array.isArray((custom as any)[key]) &&
      (fallback as any)[key]
    ) {
      result[key] = { ...(fallback as any)[key], ...(custom as any)[key] };
    } else {
      result[key] = (custom as any)[key];
    }
  }
  return result as Translations;
};

